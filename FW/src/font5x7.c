int font5x7_char_width(void) { return 6; }
int font5x7_char_height(void) { return 8; }

int font5x7_string_width(const char *s) {
    int w = 0;
    while (s && *s) {
        w += 6;
        ++s;
    }
    return w > 0 ? w - 1 : 0;
}

void font5x7_draw_char(uint8_t *fb, int w, int h, int x, int y, char c) {
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    const int gi = glyph_index(c);
    const uint8_t *glyph = kGlyphs[gi];
    for (int col = 0; col < 5; ++col) {
        const uint8_t line = glyph[col];
        for (int row = 0; row < 7; ++row) {
            if (line & (1 << row)) {
                set_pixel(fb, w, h, x + col, y + row, true);
            }
        }
    }
}
