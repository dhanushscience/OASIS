#include "font5x7.h"

#include <stdbool.h>
#include <string.h>

static void set_pixel(uint8_t *fb, int w, int h, int x, int y, bool on) {
    if (x < 0 || y < 0 || x >= w || y >= h) {
        return;
    }
    const int byte = x + (y / 8) * w;
    const uint8_t mask = 1u << (y & 7);
    if (on) {
        fb[byte] |= mask;
    } else {
        fb[byte] &= (uint8_t)~mask;
    }
}

// Minimal 5x7 glyphs for A-Z, 0-9, space, %, >
static int glyph_index(char c) {
    if (c == ' ') return 0;
    if (c >= '0' && c <= '9') return 1 + (c - '0');
    if (c >= 'A' && c <= 'Z') return 11 + (c - 'A');
    if (c == '%') return 37;
    if (c == '>') return 38;
    return 39; // ?
}

