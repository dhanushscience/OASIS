(() => {
  const PORT = 17322;
  const WS_URLS = [
    `ws://127.0.0.1:${PORT}/oasis`,
    `ws://localhost:${PORT}/oasis`
  ];
  // OASIS writes these into the published extension folder at bridge start.
  // JSON is primary; the .js form is kept for older app builds.
  const TOKEN_FILES = ["bridge-token.json", "bridge-token.js"];
  const TOKEN_TTL_MS = 5000;
  const RECONNECT_MIN_MS = 1500;
  const RECONNECT_MAX_MS = 15000;
  const HANDSHAKE_ACK_MS = 700;

  let urlIndex = 0;
  let socket = null;
  let reconnectTimer = null;
  let handshakeTimer = null;
  let queued = [];
  let lastError = "";
  let connected = false;
  let lastForwarded = "";
  let lastForwardedAt = "";
  let bridgeToken = "";
  let tokenLoadedAt = 0;
  let connecting = false;
  let handshakeAcked = false;
  let failureStreak = 0;

  // The token is generated by OASIS at runtime, so it must be READ, not IMPORTED.
  // importScripts() caches into the service worker's script resource map and is never
  // re-fetched until the extension is reinstalled — which permanently pinned an empty
  // token whenever the worker installed before OASIS had written the file.
  async function loadBridgeToken(force) {
    if (!force && bridgeToken && Date.now() - tokenLoadedAt < TOKEN_TTL_MS)
      return bridgeToken;

    for (const name of TOKEN_FILES) {
      let text;
      try {
        const url = `${chrome.runtime.getURL(name)}?t=${Date.now()}`;
        const res = await fetch(url, { cache: "no-store" });
        if (!res.ok)
          continue;
        text = await res.text();
      } catch {
        continue; // File not published by this app version — try the next shape.
      }

      let token = "";
      if (name.endsWith(".json")) {
        try {
          token = String(JSON.parse(text).token || "");
        } catch {
          token = "";
        }
      } else {
        const match = text.match(/"([A-Za-z0-9+/=_-]{16,})"/);
        token = match ? match[1] : "";
      }

      if (token) {
        bridgeToken = token;
        tokenLoadedAt = Date.now();
        return bridgeToken;
      }
    }

    return bridgeToken;
  }

  function setActionAppearance(isConnected) {
    try {
      chrome.action.setBadgeText({ text: "" });
      const suffix = isConnected ? ".png" : "-off.png";
      chrome.action.setIcon({
        path: {
          16: `icons/icon16${suffix}`,
          32: `icons/icon32${suffix}`,
          48: `icons/icon48${suffix}`
        }
      });
      chrome.action.setTitle({
        title: isConnected ? "OASIS Bridge · connected" : "OASIS Bridge · disconnected"
      });
    } catch {
      // Ignore icon update failures.
    }
  }

  function setStatus(isConnected, errorText) {
    connected = isConnected;
    if (typeof errorText === "string")
      lastError = errorText;
    try {
      setActionAppearance(isConnected);
      chrome.storage.local.set({
        oasisBridgeConnected: isConnected,
        oasisBridgeError: lastError || "",
        oasisBridgeUrl: WS_URLS[urlIndex],
        oasisLastForwarded: lastForwarded,
        oasisLastForwardedAt: lastForwardedAt
      });
    } catch {
      // Ignore UI update failures.
    }
  }

  function clearHandshakeTimer() {
    if (handshakeTimer) {
      clearTimeout(handshakeTimer);
      handshakeTimer = null;
    }
  }

  function flushQueue() {
    while (queued.length > 0 && socket && socket.readyState === WebSocket.OPEN) {
      socket.send(JSON.stringify(queued.shift()));
    }
  }

  // The server closes an unauthorized socket right after onopen, so "open" is not
  // "connected". Only an actual reply (or a quiet grace period) confirms the handshake.
  function confirmHandshake() {
    if (handshakeAcked)
      return;
    handshakeAcked = true;
    clearHandshakeTimer();
    failureStreak = 0;
    setStatus(true, "");
    flushQueue();
  }

  async function connect() {
    if (connecting)
      return;
    if (socket && (socket.readyState === WebSocket.OPEN || socket.readyState === WebSocket.CONNECTING))
      return;

    connecting = true;
    const url = WS_URLS[urlIndex];
    try {
      const token = await loadBridgeToken(false);

      try {
        socket = new WebSocket(url);
      } catch (err) {
        setStatus(false, String(err && err.message ? err.message : err));
        scheduleReconnect(true);
        return;
      }

      handshakeAcked = false;

      socket.onopen = () => {
        try {
          socket.send(JSON.stringify({
            type: "hello",
            client: "oasis-bridge-extension",
            version: "1.3.0",
            token
          }));
        } catch {
          // Ignore send race on close.
        }

        clearHandshakeTimer();
        handshakeTimer = setTimeout(() => {
          if (socket && socket.readyState === WebSocket.OPEN)
            confirmHandshake();
        }, HANDSHAKE_ACK_MS);
      };

      socket.onmessage = (ev) => {
        confirmHandshake();

        let msg;
        try {
          msg = JSON.parse(String(ev.data || ""));
        } catch {
          return;
        }
        if (!msg || typeof msg !== "object" || typeof msg.type !== "string")
          return;

        if (msg.type === "oasis.settings" || msg.type === "oasis.command")
          forwardToYouTubeTabs(msg);
      };

      socket.onclose = (ev) => {
        clearHandshakeTimer();
        const rejected = ev.code === 1008; // PolicyViolation — the app refused our token.

        if (rejected) {
          // Force a fresh read; OASIS rewrites the token file on every bridge start.
          bridgeToken = "";
          tokenLoadedAt = 0;
          failureStreak++;
          setStatus(false, "unauthorized (1008) — OASIS rejected the bridge token. "
            + "Make sure OASIS is running, then reload this extension.");
        } else if (handshakeAcked) {
          failureStreak = 0;
          setStatus(false, `closed ${ev.code || ""}`.trim());
        } else {
          failureStreak++;
          setStatus(false, `closed ${ev.code || ""}`.trim());
        }

        // Rotate the host only when the URL itself might be at fault — never after a
        // token rejection or a healthy session, both of which prove the URL works.
        scheduleReconnect(!rejected && !handshakeAcked);
      };

      socket.onerror = () => {
        setStatus(false, `websocket error (${url}) — is OASIS running with Browser Bridge enabled?`);
        try { socket.close(); } catch { /* ignore */ }
      };
    } finally {
      connecting = false;
    }
  }

  function scheduleReconnect(rotateUrl) {
    if (reconnectTimer)
      return;
    if (rotateUrl)
      urlIndex = (urlIndex + 1) % WS_URLS.length;

    const backoff = Math.min(
      RECONNECT_MIN_MS * Math.pow(2, Math.max(0, failureStreak - 1)),
      RECONNECT_MAX_MS
    );
    reconnectTimer = setTimeout(() => {
      reconnectTimer = null;
      connect();
    }, backoff);
  }

  function publish(payload) {
    connect();
    lastForwarded = payload && payload.type ? String(payload.type) : "";
    lastForwardedAt = new Date().toISOString();
    setStatus(connected, lastError);

    if (handshakeAcked && socket && socket.readyState === WebSocket.OPEN) {
      socket.send(JSON.stringify(payload));
      return;
    }
    queued.push(payload);
    if (queued.length > 40)
      queued.shift();
  }

  async function ensureContentScript(tabId) {
    try {
      await chrome.scripting.executeScript({
        target: { tabId, allFrames: false },
        files: ["content.js"]
      });
    } catch {
      // Tab may not allow scripting — ignore.
    }
    try {
      await chrome.scripting.executeScript({
        target: { tabId, allFrames: false },
        world: "MAIN",
        files: ["adskip.js"]
      });
    } catch {
      // MAIN world inject may fail on restricted pages — ignore.
    }
  }

  async function forwardToYouTubeTabs(message) {
    let tabs = [];
    try {
      tabs = await chrome.tabs.query({
        url: [
          "*://www.youtube.com/*",
          "*://youtube.com/*",
          "*://m.youtube.com/*",
          "*://music.youtube.com/*",
          "*://youtu.be/*"
        ]
      });
    } catch {
      return;
    }

    for (const tab of tabs) {
      if (tab.id == null)
        continue;

      // Hold playback boost is for normal watch videos only — skip Shorts tabs entirely.
      const cmd = message && message.type === "oasis.command" ? String(message.command || "") : "";
      if ((cmd === "playbackRate.hold2x" || cmd === "playbackRate.hold" || cmd === "playbackRate.restore")
          && typeof tab.url === "string"
          && /\/shorts\//i.test(tab.url)) {
        continue;
      }

      try {
        await chrome.tabs.sendMessage(tab.id, message);
      } catch {
        await ensureContentScript(tab.id);
        try {
          await chrome.tabs.sendMessage(tab.id, message);
        } catch {
          // Tab may not have content script yet.
        }
      }
    }
  }

  chrome.tabs.onUpdated.addListener((tabId, changeInfo, tab) => {
    if (changeInfo.status !== "complete" || !tab.url)
      return;
    if (!/youtube\.com|youtu\.be/i.test(tab.url))
      return;
    ensureContentScript(tabId);
  });

  chrome.runtime.onMessage.addListener((message, _sender, sendResponse) => {
    if (!message || typeof message !== "object")
      return;

    if (message.type === "oasis.status") {
      sendResponse({
        connected,
        lastError
      });
      return true;
    }

    if (message.type === "oasis.reconnect") {
      clearHandshakeTimer();
      if (reconnectTimer) {
        clearTimeout(reconnectTimer);
        reconnectTimer = null;
      }
      failureStreak = 0;
      bridgeToken = "";
      tokenLoadedAt = 0;
      try { if (socket) socket.close(); } catch { /* ignore */ }
      socket = null;
      connect();
      sendResponse({ ok: true });
      return true;
    }

    if (message.type === "oasis.holdRate") {
      const rate = Number(message.holdPlaybackRate);
      const holdPlaybackRate = Number.isFinite(rate)
        ? Math.min(4, Math.max(1.25, Math.round(rate * 100) / 100))
        : 2;
      chrome.storage.local.set({ holdPlaybackRate });
      forwardToYouTubeTabs({ type: "oasis.holdRate", holdPlaybackRate });
      sendResponse({ ok: true, holdPlaybackRate });
      return true;
    }

    if (typeof message.type !== "string" || !message.type.startsWith("youtube."))
      return;

    publish({
      ...message,
      source: "extension",
      ts: new Date().toISOString()
    });
  });

  try {
    chrome.alarms.create("oasis-bridge-keepalive", { periodInMinutes: 0.5 });
  } catch {
    // alarms optional
  }

  chrome.alarms.onAlarm.addListener((alarm) => {
    if (alarm.name !== "oasis-bridge-keepalive")
      return;
    connect();
    if (handshakeAcked && socket && socket.readyState === WebSocket.OPEN) {
      try {
        socket.send(JSON.stringify({ type: "ping", ts: new Date().toISOString() }));
      } catch {
        // Ignore.
      }
    }
  });

  chrome.runtime.onInstalled.addListener(() => connect());
  chrome.runtime.onStartup.addListener(() => connect());

  setStatus(false, "starting");
  connect();
})();
